import {test,expect} from '@playwright/test';
import {spawnSync} from 'node:child_process';
import path from 'node:path';

test('real persisted workspace, customer, workflow, approvals and responsive navigation',async({page})=>{
 const email=`e2e-${Date.now()}@example.com`;
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByLabel('Your name').fill('Alex Morgan');
 await page.getByLabel('Workspace name').fill('SwitchOps · Synthetic QA');
 await page.getByLabel('Work email').fill(email);
 await page.getByLabel('Password',{exact:true}).fill('test-only-strong-password!');
 await page.getByRole('button',{name:'Create workspace'}).click();
 await expect(page.getByRole('heading',{name:'Good to see you, Alex.'})).toBeVisible();
 await page.getByRole('button',{name:'Explore with labeled sample data'}).click();
 await expect(page.getByRole('button',{name:/Total customers/})).toContainText('3');
 await expect(page.locator('[data-sonner-toast]')).toHaveCount(0,{timeout:10000});
 await expect(page.getByText('Synthetic planning task')).toHaveCount(0);
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'../../docs/screenshots/overview-desktop.png',fullPage:true});
 await page.getByRole('link',{name:'Customers',exact:true}).click();
 await expect(page.getByText('Acme Solutions').first()).toBeVisible();
 await page.getByRole('button',{name:'Add customer'}).first().click();
 await page.getByLabel('Name',{exact:true}).fill('Synthetic · Test Customer');
 await page.getByLabel('Email',{exact:true}).fill('customer@example.test');
 await page.getByLabel('Notes').fill('Synthetic customer created by browser test.');
 await page.getByRole('button',{name:'Save customer'}).click();
 await expect(page.getByRole('button',{name:'Edit Synthetic · Test Customer',exact:true})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('button',{name:'Edit Synthetic · Test Customer',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Tasks',exact:true}).click();
 await page.getByRole('button',{name:'Board',exact:true}).click();
 await expect(page.getByRole('heading',{name:/In progress/})).toBeVisible();
 await page.getByRole('link',{name:'Command Center',exact:true}).click();
 await page.getByRole('textbox',{name:'Business request'}).fill('Prepare a synthetic customer proposal and ask before sending anything.');
 await page.getByRole('combobox',{name:'Customer',exact:true}).selectOption({label:'Synthetic · Test Customer'});
 await page.getByRole('button',{name:'Submit business request'}).click();
 await expect(page.getByRole('heading',{name:'The request',exact:true})).toBeVisible();
 await expect(page.getByText('Business request saved. Waiting for Switch dispatch.')).toBeVisible();
 const root=path.resolve('../..');const python=path.join(root,'.venv',process.platform==='win32'?'Scripts/python.exe':'bin/python');
 const fixture=spawnSync(python,['scripts/e2e-fixture.py',email],{cwd:root,env:{...process.env,PYTHONPATH:[path.join(root,'services/api'),path.join(root,'services')].join(path.delimiter),DATABASE_URL:'sqlite+aiosqlite:///./.data/e2e.db',ENVIRONMENT:'test'},encoding:'utf8'});
 expect(fixture.status,fixture.stderr).toBe(0);
 await page.getByRole('link',{name:/^Approvals/}).click();
 await page.getByRole('button',{name:'Review proposal'}).click();
 await expect(page.getByText('SYNTHETIC TEST FIXTURE.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Approve this version'}).click();
 await page.getByRole('button',{name:'Approved',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Synthetic · Approval review fixture'})).toBeVisible();
 await page.getByRole('link',{name:'Integrations',exact:true}).click();
 await page.getByRole('button',{name:'Test connection'}).first().click();
 await expect(page.getByText(/Connection test failed/)).toBeVisible();
 await expect(page.locator('[data-sonner-toast]')).toHaveCount(0,{timeout:10000});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('link',{name:'Overview',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Good to see you, Alex.'})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'../../docs/screenshots/overview-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.setViewportSize({width:1440,height:1100});
 for(const route of ['/agents','/rooms','/calendar','/knowledge','/analytics','/activity','/team','/settings','/inbox']){
   await page.goto(route);await expect(page.locator('.page-heading h1')).toBeVisible();
 }
 await page.getByRole('button',{name:'Use dark theme'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 expect(errors).toEqual([]);
});
